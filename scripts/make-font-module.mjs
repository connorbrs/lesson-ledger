// Developer tool, not part of the app or dist: turns a TrueType font file into a TypeScript module that exports
// the file as one standard base64 string (D-01, plan 04-04). The PDF engine registers it with addFileToVFS.
//
//   node scripts/make-font-module.mjs <font.ttf> <ExportName> <output.ts>
//
// The font is a Noto Sans subset (SIL Open Font License 1.1, see src/pdf/fonts/OFL.txt) cut once with fontTools.
import { readFileSync, writeFileSync } from 'node:fs';

const usage = 'Usage: node scripts/make-font-module.mjs <font.ttf> <ExportName> <output.ts>';
const [fontPath, exportName, outPath] = process.argv.slice(2);
if (!fontPath || !exportName || !outPath || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(exportName)) {
  console.error(usage);
  process.exit(1);
}

const bytes = readFileSync(fontPath);
if (bytes.length < 4 || bytes[0] !== 0x00 || bytes[1] !== 0x01 || bytes[2] !== 0x00 || bytes[3] !== 0x00) {
  console.error(`${fontPath} is not a TrueType font (the first four bytes must be 00 01 00 00).`);
  process.exit(1);
}

const header = [
  '// GENERATED by scripts/make-font-module.mjs. Do not edit.',
  '// Noto Sans subset (Latin, Latin-1, Latin Extended-A and a few punctuation marks), SIL Open Font License 1.1.',
  '// Licence text: src/pdf/fonts/OFL.txt',
].join('\n');
writeFileSync(outPath, `${header}\nexport const ${exportName} =\n  '${bytes.toString('base64')}';\n`);
console.log(`Wrote ${outPath} (${bytes.length} bytes of font).`);
